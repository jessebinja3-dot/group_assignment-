// Question 4: Basic Variables
// Declares variables for name, age and GPA, then displays them.
 
#include <iostream>
using namespace std;
 
int main() {
    string name = "Moussa Martinez"; // string variable
    int age = 21;                   // integer variable
    float gpa = 3.75;               // floating-point variable
 
    cout << "Name : " << name << endl;
    cout << "Age  : " << age << endl;
    cout << "GPA  : " << gpa << endl;
 
    return 0;
}
